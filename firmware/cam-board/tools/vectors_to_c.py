#!/usr/bin/env python3
"""Convert protocol/vectors/vectors.json into test/test_wire/vectors_gen.h for the camera board's
native Unity tests. Run from anywhere; regenerate whenever the golden vectors change:

    python3 firmware/cam-board/tools/vectors_to_c.py
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "../../../protocol/vectors/vectors.json"
OUT = HERE / "../test/test_wire/vectors_gen.h"

# Only the packet types the camera board builds or parses.
TYPES = {"BEAT", "FRAME", "PING", "PONG", "CUE", "PROFILE"}


def c_bytes(b: bytes) -> str:
    if not b:
        return "{0}"
    return "{" + ",".join(f"0x{x:02x}" for x in b) + "}"


def main() -> None:
    vecs = json.loads(SRC.read_text())
    out = [
        "// GENERATED by tools/vectors_to_c.py from protocol/vectors/vectors.json. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
    ]
    counts = {}
    for v in vecs:
        t = v["type"]
        if t not in TYPES:
            continue
        name = v["name"].upper()
        raw = bytes.fromhex(v["hex"])
        f = v["fields"]
        counts[t] = counts.get(t, 0) + 1
        out.append(f"/* {v['name']} */")
        out.append(f"static const uint8_t VEC_{name}[] = {c_bytes(raw)};")
        out.append(f"static const size_t VEC_{name}_LEN = {len(raw)};")
        out.append(f"static const uint32_t VEC_{name}_SEQ = {v['seq']}u;")
        if t == "FRAME":
            data = bytes.fromhex(f["data"])
            out.append(f"static const uint8_t VEC_{name}_DATA[] = {c_bytes(data)};")
            for k in ("frame_id", "w", "h", "total_len", "offset", "chunk_idx", "chunk_count"):
                out.append(f"static const uint32_t VEC_{name}_{k.upper()} = {f[k]}u;")
            out.append(f"static const uint64_t VEC_{name}_T_CAP_US = {f['t_cap_us']}ull;")
            out.append(f"static const uint16_t VEC_{name}_CHUNK_LEN = {len(data)}u;")
        elif t == "BEAT":
            for k in ("board", "reset_reason", "faults", "heap_kb"):
                out.append(f"static const uint32_t VEC_{name}_{k.upper()} = {f[k]}u;")
            out.append(f"static const uint64_t VEC_{name}_T_US = {f['t_us']}ull;")
            out.append(f"static const int8_t VEC_{name}_RSSI_DBM = {f['rssi_dbm']};")
            out.append(f"static const int8_t VEC_{name}_TEMP_C = {f['temp_c']};")
        elif t in ("PING", "PONG"):
            for k, val in f.items():
                out.append(f"static const uint64_t VEC_{name}_{k.upper()} = {val}ull;")
        out.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.resolve()} {counts}")


if __name__ == "__main__":
    main()
