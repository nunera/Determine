#!/usr/bin/env python3
"""Convert protocol/vectors/vectors.json into test/test_cue_logic/vectors.h (C arrays).

Run from firmware/cue-board:  python3 tools/vectors_to_c.py
The generated header is committed; regenerate whenever the golden vectors change.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent.parent
SRC = HERE.parent.parent / "protocol" / "vectors" / "vectors.json"
DST = HERE / "test" / "test_cue_logic" / "vectors.h"


def c_bytes(hexstr):
    b = bytes.fromhex(hexstr)
    return ", ".join(f"0x{x:02x}" for x in b), len(b)


def main():
    vectors = json.loads(SRC.read_text())
    out = [
        "// GENERATED by tools/vectors_to_c.py from protocol/vectors/vectors.json. Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for v in vectors:
        name = v["name"].upper()
        data, n = c_bytes(v["hex"])
        out.append(f"/* {v['name']} ({v['type']}, seq {v['seq']}) */")
        out.append(f"static const uint8_t VEC_{name}[{n}] = {{{data}}};")
        out.append(f"#define VEC_{name}_SEQ {v['seq']}u")
        for k, val in v["fields"].items():
            if isinstance(val, list):
                out.append(f"static const int32_t VEC_{name}_{k.upper()}[{len(val)}] = {{{', '.join(map(str, val))}}};")
            elif isinstance(val, int):
                suffix = "ll" if val < 0 else "ull"
                out.append(f"#define VEC_{name}_{k.upper()} ({val}{suffix})")
        out.append("")
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text("\n".join(out))
    print(f"wrote {DST} ({len(vectors)} vectors)")


if __name__ == "__main__":
    main()
