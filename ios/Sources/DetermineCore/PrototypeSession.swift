import Foundation

public enum OutputMode: String, CaseIterable, Codable, Sendable {
    case stereo, singleEar, hapticOnly

    public var label: String {
        switch self {
        case .stereo: return "Stereo"
        case .singleEar: return "Single ear"
        case .hapticOnly: return "Haptics only"
        }
    }
}

public enum DemoScenario: String, CaseIterable, Sendable {
    case noHardware, far, mid, near, unknown, boardLost, headsetLost

    public var label: String {
        switch self {
        case .noHardware: return "No hardware (default)"
        case .far: return "Synthetic far · 1050 mm"
        case .mid: return "Synthetic mid · 700 mm"
        case .near: return "Synthetic near · 350 mm"
        case .unknown: return "Synthetic range unknown"
        case .boardLost: return "Synthetic board disconnected"
        case .headsetLost: return "Synthetic headset disconnected"
        }
    }
}

public enum PrototypeState: String, Sendable {
    case stopped, starting, ready, degraded, unavailable, paused

    public var label: String {
        switch self {
        case .stopped: return "Stopped"
        case .starting: return "Demo: Starting"
        case .ready: return "Demo: Ready"
        case .degraded: return "Demo: Degraded"
        case .unavailable: return "Unavailable"
        case .paused: return "Demo: Paused"
        }
    }
}

public enum CalibrationStep: String, Sendable {
    case intro, fit, threshold, level, balance, verify, done, failed
}

public enum Ear: String, CaseIterable, Sendable {
    case left, right

    public var label: String { self == .left ? "Left" : "Right" }
}

// An in-memory, synthetic analogue of the Android 2-down-1-up staircase.
// No tones or warning cues are generated by this type.
private struct DemoStaircase: Sendable {
    private(set) var levelDb = -60
    private(set) var trials = 0
    private(set) var done = false
    private(set) var unusable = false
    private(set) var thresholdDb: Int?
    private var reversalLevels: [Int] = []
    private var lastDirection = 0
    private var consecutiveHeard = 0

    mutating func answer(_ heard: Bool) {
        guard !done else { return }
        trials += 1
        let direction: Int
        if heard {
            consecutiveHeard += 1
            if consecutiveHeard < 2 { checkTrialLimit(); return }
            consecutiveHeard = 0
            direction = -1
        } else {
            consecutiveHeard = 0
            if levelDb >= -10 {
                unusable = true
                done = true
                return
            }
            direction = 1
        }
        if lastDirection != 0 && direction != lastDirection {
            reversalLevels.append(levelDb)
            if reversalLevels.count == 8 {
                done = true
                computeThreshold()
                return
            }
        }
        lastDirection = direction
        let step = reversalLevels.count < 2 ? 6 : 2
        levelDb = min(-10, max(-90, levelDb + direction * step))
        checkTrialLimit()
    }

    private mutating func checkTrialLimit() {
        guard trials >= 80 && !done else { return }
        done = true
        if reversalLevels.count < 4 {
            if levelDb <= -90 { reversalLevels.append(-90) }
            else { unusable = true }
        }
        computeThreshold()
    }

    private mutating func computeThreshold() {
        guard !unusable else { return }
        let values = reversalLevels.count > 2 ? reversalLevels.dropFirst(2) : reversalLevels[...]
        guard !values.isEmpty else { unusable = true; return }
        // Kotlin Math.round: ties toward positive infinity, including negative dBFS values.
        thresholdDb = Int((Double(values.reduce(0, +)) / Double(values.count) + 0.5).rounded(.down))
    }
}

private struct DemoProfile: Sendable {
    var mode: OutputMode
    var thresholds: [[Int?]]
    var sensationLevelDb: Int
    var balanceDb: Int
    var verifiedTrials: Int
    var verifiedCorrect: Int

    func usable(_ ear: Ear) -> Bool {
        thresholds[ear == .left ? 0 : 1].allSatisfy { $0 != nil }
    }

    func rawLevel(_ ear: Ear, band: Int) -> Int? {
        thresholds[ear == .left ? 0 : 1][band].map { $0 + sensationLevelDb }
    }

    func level(_ ear: Ear, band: Int) -> Int? {
        guard let raw = rawLevel(ear, band: band) else { return nil }
        let offset = ear == .left ? -balanceDb / 2 : balanceDb - balanceDb / 2
        return min(-10, raw + offset)
    }
}

public struct PrototypeCalibration: Sendable {
    public private(set) var step: CalibrationStep = .fit
    public private(set) var ear: Ear = .left
    public private(set) var frequencyHz: Int = 500
    public private(set) var levelDb: Int = -60
    public private(set) var balanceDb: Int = 0
    public private(set) var balanceConfirms: Int = 0
    public private(set) var verifyTrials: Int = 0
    public private(set) var verifyCorrect: Int = 0
    public private(set) var verificationEar: Ear = .left
    public private(set) var failureReason: String?
    public private(set) var resultMode: OutputMode?
    public let ceilingDb: Int = -10

    private static let frequencies = [500, 1000, 2000]
    private static let verificationOrder: [Ear] = [.left, .right, .left, .right, .right]
    private var staircase = DemoStaircase()
    private var index = 0
    private var thresholds: [[Int?]] = Array(repeating: Array(repeating: nil, count: 3), count: 2)
    private var sensationLevelDb = 15
    private var firstBalance = 0
    private var profile: DemoProfile?

    fileprivate init() {}

    fileprivate mutating func fit(weakerEar: Ear?) {
        guard step == .fit else { return }
        // The fit answer is a user note, not an inferred threshold or a hearing diagnosis.
        _ = weakerEar
        index = 0
        beginThreshold()
    }

    private mutating func beginThreshold() {
        staircase = DemoStaircase()
        ear = index < 3 ? .left : .right
        frequencyHz = Self.frequencies[index % 3]
        levelDb = staircase.levelDb
        step = .threshold
    }

    fileprivate mutating func answerHeard(_ heard: Bool) {
        guard step == .threshold else { return }
        staircase.answer(heard)
        levelDb = staircase.levelDb
        guard staircase.done else { return }
        let side = index / 3
        thresholds[side][index % 3] = staircase.thresholdDb
        if staircase.unusable {
            // Like Android, one undetected band disables the rest of that ear;
            // an unplayed stimulus must NEVER be counted as "not heard".
            index = (side + 1) * 3
        } else {
            index += 1
        }
        if index < 6 { beginThreshold() }
        else { step = .level }
    }

    fileprivate mutating func setSensationLevel(_ db: Int) {
        guard step == .level, (10...20).contains(db) else { return }
        sensationLevelDb = db
        let leftUsable = thresholds[0].allSatisfy { $0 != nil }
        let rightUsable = thresholds[1].allSatisfy { $0 != nil }
        if !leftUsable && !rightUsable { finish(.hapticOnly) }
        else if !leftUsable || !rightUsable { finish(.singleEar) }
        else { step = .balance; ear = .left; levelDb = balancedLevel(.left) }
    }

    private func balancedLevel(_ ear: Ear) -> Int {
        let raw = thresholds[ear == .left ? 0 : 1][1].map { $0 + sensationLevelDb } ?? -10
        let offset = ear == .left ? -balanceDb / 2 : balanceDb - balanceDb / 2
        return min(ceilingDb, raw + offset)
    }

    fileprivate mutating func nudgeBalance(_ delta: Int) {
        guard step == .balance else { return }
        // Bound the requested change before adding it, so even Int.max/min are safe.
        balanceDb = min(12, max(-12, balanceDb + min(24, max(-24, delta))))
        ear = ear == .left ? .right : .left
        levelDb = balancedLevel(ear)
    }

    fileprivate mutating func confirmBalance() {
        guard step == .balance else { return }
        balanceConfirms += 1
        if balanceConfirms == 1 {
            firstBalance = balanceDb
            ear = ear == .left ? .right : .left
            levelDb = balancedLevel(ear)
        } else {
            balanceDb = Int((Double(firstBalance + balanceDb) / 2 + 0.5).rounded(.down))
            step = .verify
            presentVerification()
        }
    }

    private mutating func presentVerification() {
        verificationEar = Self.verificationOrder[verifyTrials]
        ear = verificationEar
        levelDb = balancedLevel(ear)
    }

    fileprivate mutating func answerSide(_ side: Ear) {
        guard step == .verify else { return }
        verifyTrials += 1
        if side == verificationEar { verifyCorrect += 1 }
        if verifyTrials < 5 { presentVerification(); return }
        let atCeiling = thresholds.contains { side in
            side.contains { threshold in
                guard let threshold else { return false }
                return threshold + sensationLevelDb >= ceilingDb
            }
        }
        finish(verifyCorrect >= 4 && !atCeiling ? .stereo : .singleEar)
    }

    fileprivate mutating func chooseHapticOnly() {
        guard step != .failed && step != .done else { return }
        finish(.hapticOnly)
    }

    private mutating func finish(_ mode: OutputMode) {
        step = .done
        resultMode = mode
        profile = DemoProfile(mode: mode, thresholds: thresholds, sensationLevelDb: sensationLevelDb,
                              balanceDb: balanceDb, verifiedTrials: verifyTrials, verifiedCorrect: verifyCorrect)
    }

    fileprivate mutating func fail(_ reason: String) {
        guard step != .failed else { return }
        step = .failed
        failureReason = reason
        resultMode = nil
        profile = nil
    }

    fileprivate var result: DemoProfile? { step == .done ? profile : nil }

    fileprivate mutating func replay() {
        guard step == .threshold || step == .balance || step == .verify else { return }
        // The displayed synthetic ear/level remain unchanged. No sound is played.
    }
}

public struct PrototypeSession: Sendable {
    public var spearcons: Bool = true
    public var describeEnabled: Bool = false
    public private(set) var running = false
    public private(set) var paused = false
    public private(set) var mode: OutputMode = .stereo
    public private(set) var hapticMax = 255
    public private(set) var scenario: DemoScenario = .noHardware
    public private(set) var state: PrototypeState = .stopped
    public private(set) var reason = "Stopped. No boards connected; this is an interactive synthetic demo."
    public private(set) var calibration: PrototypeCalibration?
    public private(set) var describeMessage: String?

    private var profile: DemoProfile?
    private var pausedBeforeCalibration: Bool?

    public init() {}

    public var distanceMm: Int? {
        switch scenario {
        case .far: return 1050
        case .mid, .headsetLost: return 700
        case .near: return 350
        case .noHardware, .unknown, .boardLost: return nil
        }
    }

    public var rangeStatus: String {
        switch scenario {
        case .far, .mid, .near, .headsetLost: return "Synthetic valid range"
        case .unknown: return "Synthetic range unknown — not clear"
        case .noHardware: return "Unavailable — no boards connected"
        case .boardLost: return "Unavailable — synthetic board disconnected"
        }
    }

    public var headsetReady: Bool { scenario != .noHardware && scenario != .headsetLost }
    public var cueBoardReady: Bool { scenario != .noHardware && scenario != .boardLost }
    public var cameraBoardReady: Bool { scenario != .noHardware && scenario != .boardLost }

    public var bandLabel: String? {
        guard running, !paused, calibration == nil || calibration?.step == .failed,
              state == .ready, cueBoardReady, cameraBoardReady,
              (mode == .hapticOnly || headsetReady) else { return nil }
        switch scenario {
        case .near: return "Synthetic near warning · 350 mm"
        case .mid, .headsetLost: return "Synthetic mid warning · 700 mm"
        case .far: return "Synthetic far warning · 1050 mm"
        case .noHardware, .unknown, .boardLost: return nil
        }
    }

    public var profileSummary: String {
        guard let profile else { return "Demo profile: not calibrated this session" }
        let checks = profile.verifiedTrials > 0
            ? "synthetic side checks \(profile.verifiedCorrect) of \(profile.verifiedTrials)"
            : "no side checks"
        if profile.mode == .hapticOnly {
            return "Demo profile: Haptics only, \(checks). Not a hearing test."
        }
        let virtualLevels = Ear.allCases.compactMap { ear -> String? in
            guard profile.usable(ear), let db = profile.level(ear, band: 1) else { return nil }
            return "\(ear.label.lowercased()) \(db) dBFS"
        }.joined(separator: ", ")
        return "Demo profile: \(profile.mode.label), \(checks). Synthetic 1 kHz levels: \(virtualLevels) (ceiling −10 dBFS). Not a hearing test."
    }

    public mutating func start() {
        guard !running else { return }
        running = true
        paused = false
        describeMessage = nil
        refreshState()
    }

    public mutating func stop() {
        running = false
        paused = false
        profile = nil
        calibration = nil
        pausedBeforeCalibration = nil
        describeMessage = nil
        state = .stopped
        reason = "Stopped. No boards connected; this is an interactive synthetic demo."
    }

    public mutating func enterBackground() { stop() }

    public mutating func setPaused(_ value: Bool) {
        guard running, calibration == nil || calibration?.step == .failed else { return }
        paused = value
        if value { describeMessage = nil }
        refreshState()
    }

    public mutating func setMode(_ value: OutputMode) {
        if value != mode { profile = nil }
        mode = value
        refreshState()
    }

    public mutating func setHapticMax(_ value: Int) { hapticMax = min(255, max(1, value)) }

    public mutating func selectScenario(_ value: DemoScenario) {
        scenario = value
        // Never carry an answer or a pending result across loss of either synthetic route.
        if calibration != nil && (!headsetReady || !cueBoardReady || !cameraBoardReady) {
            calibration?.fail("Synthetic route lost. No demo profile saved; reconnect and restart calibration.")
            if let savedPause = pausedBeforeCalibration { paused = savedPause; pausedBeforeCalibration = nil }
        }
        describeMessage = nil
        refreshState()
    }

    public mutating func requestDescription() {
        guard describeEnabled else {
            describeMessage = "Describe is off. No image was captured or uploaded."
            return
        }
        describeMessage = "Unavailable in this demo: camera capture and redaction are not implemented. No image was captured or uploaded."
    }

    public mutating func beginCalibration() {
        guard running, headsetReady, cueBoardReady, cameraBoardReady else { return }
        if calibration != nil && calibration?.step != .failed { return }
        pausedBeforeCalibration = paused
        paused = true
        describeMessage = nil
        calibration = PrototypeCalibration()
        refreshState()
    }

    public mutating func fitCalibration(weakerEar: Ear?) {
        guard calibrationCanProceed else { return }
        calibration?.fit(weakerEar: weakerEar)
    }

    public mutating func answerHeard(_ heard: Bool) {
        guard calibrationCanProceed else { return }
        calibration?.answerHeard(heard)
    }

    public mutating func setSensationLevel(_ value: Int) {
        guard calibrationCanProceed else { return }
        calibration?.setSensationLevel(value)
    }

    public mutating func nudgeBalance(_ delta: Int) {
        guard calibrationCanProceed else { return }
        calibration?.nudgeBalance(delta)
    }

    public mutating func confirmBalance() {
        guard calibrationCanProceed else { return }
        calibration?.confirmBalance()
    }

    public mutating func answerSide(_ side: Ear) {
        guard calibrationCanProceed else { return }
        calibration?.answerSide(side)
    }

    public mutating func replayCalibration() {
        guard calibrationCanProceed else { return }
        calibration?.replay()
    }

    public mutating func chooseHapticOnly() {
        guard calibrationCanProceed else { return }
        calibration?.chooseHapticOnly()
    }

    public mutating func applyCalibration() {
        guard calibrationCanProceed, let result = calibration?.result else { return }
        profile = result
        mode = result.mode
        finishCalibration()
    }

    public mutating func cancelCalibration() {
        guard calibration != nil else { return }
        finishCalibration()
    }

    private var calibrationCanProceed: Bool {
        running && headsetReady && cueBoardReady && cameraBoardReady &&
            calibration != nil && calibration?.step != .failed
    }

    private mutating func finishCalibration() {
        calibration = nil
        if let savedPause = pausedBeforeCalibration { paused = savedPause }
        pausedBeforeCalibration = nil
        refreshState()
    }

    private mutating func refreshState() {
        guard running else { return }
        if !cueBoardReady || !cameraBoardReady {
            state = .unavailable
            reason = scenario == .noHardware
                ? "No cue board or camera board connected. No Bluetooth headset connected. Demo cannot provide warnings."
                : "Synthetic board disconnected. Demo warnings unavailable; a missing board is never a clear path."
        } else if !headsetReady && mode != .hapticOnly {
            state = .unavailable
            reason = "Synthetic headset disconnected. Warning sounds unavailable; no phone-speaker fallback."
        } else if paused {
            state = .paused
            reason = calibration == nil || calibration?.step == .failed
                ? "Demo warnings paused." : "Demo warnings paused during synthetic calibration."
        } else if scenario == .unknown {
            state = .degraded
            reason = "Synthetic forward range unknown. No distance or clear-path claim."
        } else {
            state = .ready
            reason = mode == .hapticOnly && !headsetReady
                ? "Synthetic haptics-only scenario; headset not required. No hardware is connected."
                : "Synthetic scenario only. No hardware is connected and no warnings are played."
        }
    }
}
